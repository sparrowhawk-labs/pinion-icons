#!/usr/bin/env node
/**
 * build-icon-data.mjs — purge-style icon data bundler for <pn-icon auto>.
 *
 * Collects the SVG source of every variant the per-tune map can request
 * (Solar: bold-duotone / linear / bold / outline / line-duotone / broken,
 * plus `pixel` from pixelarticons) for the given concept names, and emits a
 * plain ES module `{ name: { variant: svgString } }` to register at runtime
 * via `PnIcon.register()`. No runtime HTTP — everything is bundled.
 *
 * Names resolve from resources/icons/solar first, then solar-extra (which
 * shares the same 6 styles). A name missing from pixelarticons falls back to
 * the Solar `bold` variant for the `pixel` key, with a warning.
 *
 * Usage:
 *   node bin/build-icon-data.mjs --out path/to/pn-icon-data.js name1 name2 …
 *
 * The emitted SVG strings are the raw icon files (trimmed) — identical input
 * to what <x-i> inlines at SSR; per-instance attributes (class, size, …) are
 * applied by <pn-icon> at render time, matching the Blade attribute merge.
 */
import { readFileSync, existsSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ICONS_DIR = resolve(dirname(fileURLToPath(import.meta.url)), '../resources/icons');

// Solar stroke variants required by the tune map (see resources/js/pn-icon.js).
const SOLAR_VARIANTS = ['bold-duotone', 'linear', 'bold', 'outline', 'line-duotone', 'broken'];

const args = process.argv.slice(2);
const outIdx = args.indexOf('--out');
if (outIdx === -1 || !args[outIdx + 1]) {
    console.error('usage: node bin/build-icon-data.mjs --out <file.js> <name> [<name> …]');
    process.exit(1);
}
const outFile = resolve(args[outIdx + 1]);
const names = args.filter((a, i) => i !== outIdx && i !== outIdx + 1 && !a.startsWith('--'));
if (names.length === 0) {
    console.error('build-icon-data: no icon names given');
    process.exit(1);
}

const readSvg = (path) => readFileSync(path, 'utf8').trim();

const data = {};
const warnings = [];

for (const name of names) {
    const variants = {};

    for (const variant of SOLAR_VARIANTS) {
        const solar = join(ICONS_DIR, 'solar', `${name}-${variant}.svg`);
        const extra = join(ICONS_DIR, 'solar-extra', `${name}-${variant}.svg`);
        if (existsSync(solar)) {
            variants[variant] = readSvg(solar);
        } else if (existsSync(extra)) {
            variants[variant] = readSvg(extra);
        } else {
            warnings.push(`missing Solar variant: ${name}-${variant}`);
        }
    }

    const pixel = join(ICONS_DIR, 'pixelarticons', `${name}.svg`);
    if (existsSync(pixel)) {
        variants.pixel = readSvg(pixel);
    } else if (variants.bold) {
        variants.pixel = variants.bold;
        warnings.push(`no pixelarticons glyph for "${name}" — pixel falls back to Solar bold`);
    } else {
        warnings.push(`no pixel source at all for "${name}"`);
    }

    if (Object.keys(variants).length === 0) {
        warnings.push(`icon "${name}" not found in any library — skipped`);
        continue;
    }
    data[name] = variants;
}

for (const w of warnings) console.warn(`[build-icon-data] WARN: ${w}`);

const banner = '// AUTO-GENERATED by pinion-icons bin/build-icon-data.mjs — do not edit.\n'
    + `// Icons: ${Object.keys(data).join(', ')}\n`;
mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, `${banner}export default ${JSON.stringify(data, null, 2)};\n`);
console.log(`[build-icon-data] wrote ${Object.keys(data).length} icons × up to ${SOLAR_VARIANTS.length + 1} variants → ${outFile}`);
